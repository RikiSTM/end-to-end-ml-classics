import logging
import pandas as pd
import numpy as np
import mlflow
from sklearn.metrics import f1_score, accuracy_score
from fairlearn.metrics import MetricFrame, demographic_parity_difference, equalized_odds_difference

# Configure standard logger for production tracking
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def evaluate_and_log_fairness(y_true: pd.Series, y_pred: np.ndarray, sensitive_feature: pd.Series, feature_name: str) -> None:
    """
    Evaluates model fairness metrics across sensitive groups and logs them to MLflow.

    Args:
        y_true (pd.Series): Ground truth target labels.
        y_pred (np.ndarray): Binary predictions generated by the model.
        sensitive_feature (pd.Series): The sensitive feature column (e.g., gender, SeniorCitizen).
        feature_name (str): The name of the sensitive feature for MLflow logging context.

    Raises:
        ValueError: If input arrays have inconsistent lengths.
    """
    try:
        # Validate data consistency before processing
        if len(y_true) != len(y_pred) or len(y_true) != len(sensitive_feature):
            raise ValueError("Input arrays (y_true, y_pred, sensitive_feature) must have the same length.")

        logger.info(f"Initiating fairness evaluation on sensitive feature: {feature_name}")

        # 1. Evaluate Disparities (Differences between groups)
        # Calculates the maximum difference in selection rates
        dp_diff = demographic_parity_difference(y_true, y_pred, sensitive_features=sensitive_feature)
        
        # Calculates the maximum difference in true/false positive rates
        eo_diff = equalized_odds_difference(y_true, y_pred, sensitive_features=sensitive_feature)

        # 2. Comprehensive Metric Frame Analysis
        # Allows us to see the F1 Score and Accuracy broken down by each demographic group
        metrics_dict = {
            "accuracy": accuracy_score,
            "f1": f1_score
        }
        
        metric_frame = MetricFrame(
            metrics=metrics_dict,
            y_true=y_true,
            y_pred=y_pred,
            sensitive_features=sensitive_feature
        )

        logger.info(f"\nFairness Breakdown for {feature_name}:\n{metric_frame.by_group}")
        
        for group_name, metrics_row in metric_frame.by_group.iterrows():
                # Membersihkan nama grup agar aman jadi nama variabel (misal: spasi jadi underscore)
                clean_group = str(group_name).replace(" ", "_").lower()
                
                # Log metrik per grup ke MLflow
                mlflow.log_metric(f"{feature_name}_{clean_group}_accuracy", metrics_row['accuracy'])
                mlflow.log_metric(f"{feature_name}_{clean_group}_f1", metrics_row['f1'])

        # 3. Log Disparity Metrics to MLflow
        mlflow.log_metric(f"{feature_name}_demographic_parity_diff", dp_diff)
        mlflow.log_metric(f"{feature_name}_equalized_odds_diff", eo_diff)
        
        logger.info(f"Successfully logged fairness metrics for {feature_name} to MLflow.")

    except Exception as e:
        logger.error(f"Fairness evaluation failed for {feature_name}: {str(e)}")
        raise